const defaultLanguage = 'en';

export function getTranslations(language = defaultLanguage) {
  return translations[language] || translations[defaultLanguage];
}

export function getSupportedLanguages() {
  return Object.keys(translations);
}

export function isSupportedLanguage(language) {
  return Object.prototype.hasOwnProperty.call(translations, language);
}

export function getDefaultLanguage() {
  return defaultLanguage;
}

export function pickLocalized(value, language = defaultLanguage) {
  if (value === null || value === undefined) return '';
  if (typeof value === 'string') return value;
  if (Array.isArray(value)) {
    return value.map((entry) => pickLocalized(entry, language));
  }
  if (typeof value === 'object') {
    const localized = value[language];
    if (typeof localized === 'string' || Array.isArray(localized)) {
      return pickLocalized(localized, language);
    }
    const fallback = value[defaultLanguage];
    if (fallback !== undefined) return pickLocalized(fallback, defaultLanguage);
    return '';
  }
  return String(value);
}

export function localizeContentTree(value, language = defaultLanguage) {
  if (value === null || value === undefined) return value;
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') return value;
  if (Array.isArray(value)) return value.map((entry) => localizeContentTree(entry, language));
  if (typeof value === 'object') {
    const hasLanguageKeys = isSupportedLanguage(Object.keys(value)[0]) && Object.keys(value).every(isSupportedLanguage);
    if (hasLanguageKeys) return pickLocalized(value, language);
    const localized = {};
    for (const [key, child] of Object.entries(value)) {
      localized[key] = localizeContentTree(child, language);
    }
    return localized;
  }
  return value;
}
